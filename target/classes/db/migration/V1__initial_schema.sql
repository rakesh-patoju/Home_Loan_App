CREATE TABLE app_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email VARCHAR(254) NOT NULL, password_hash VARCHAR(100) NOT NULL,
 full_name VARCHAR(100) NOT NULL, role VARCHAR(20) NOT NULL, enabled BOOLEAN NOT NULL, created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
 CONSTRAINT uk_user_email UNIQUE(email), CONSTRAINT ck_user_role CHECK(role IN ('CUSTOMER','LOAN_OFFICER','ADMIN'))
);
CREATE TABLE customers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id BIGINT NOT NULL,mobile VARCHAR(15) NOT NULL,date_of_birth DATE NOT NULL,
 address VARCHAR(500) NOT NULL,employment_type VARCHAR(20) NOT NULL,monthly_income DECIMAL(15,2) NOT NULL,
 CONSTRAINT uk_customer_user UNIQUE(user_id),CONSTRAINT fk_customer_user FOREIGN KEY(user_id) REFERENCES app_users(id),
 CONSTRAINT ck_customer_income CHECK(monthly_income>=0),CONSTRAINT ck_customer_employment CHECK(employment_type IN ('SALARIED','SELF_EMPLOYED'))
);
CREATE TABLE loan_products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,product_name VARCHAR(100) NOT NULL,minimum_loan_amount DECIMAL(15,2) NOT NULL,
 maximum_loan_amount DECIMAL(15,2) NOT NULL,interest_rate DECIMAL(5,2) NOT NULL,minimum_tenure_months INT NOT NULL,
 maximum_tenure_months INT NOT NULL,description VARCHAR(1000) NOT NULL,active BOOLEAN NOT NULL,
 CONSTRAINT uk_product_name UNIQUE(product_name),CONSTRAINT ck_product_amount CHECK(minimum_loan_amount>0 AND maximum_loan_amount>=minimum_loan_amount),
 CONSTRAINT ck_product_rate CHECK(interest_rate>=0 AND interest_rate<=30),CONSTRAINT ck_product_tenure CHECK(minimum_tenure_months>=12 AND maximum_tenure_months<=360 AND maximum_tenure_months>=minimum_tenure_months)
);
CREATE TABLE loan_applications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,reference_number VARCHAR(40) NOT NULL,customer_id BIGINT NOT NULL,loan_product_id BIGINT NOT NULL,
 assigned_officer_id BIGINT,requested_loan_amount DECIMAL(15,2) NOT NULL,tenure_months INT NOT NULL,monthly_income DECIMAL(15,2) NOT NULL,
 employment_type VARCHAR(20) NOT NULL,existing_emi DECIMAL(15,2) NOT NULL,interest_rate DECIMAL(5,2) NOT NULL,
 application_date TIMESTAMP(6) WITH TIME ZONE NOT NULL,status VARCHAR(30) NOT NULL,idempotency_key VARCHAR(100) NOT NULL,request_fingerprint VARCHAR(64) NOT NULL,version BIGINT NOT NULL,
 CONSTRAINT uk_application_reference UNIQUE(reference_number),CONSTRAINT uk_customer_idempotency UNIQUE(customer_id,idempotency_key),
 CONSTRAINT fk_application_customer FOREIGN KEY(customer_id) REFERENCES customers(id),CONSTRAINT fk_application_product FOREIGN KEY(loan_product_id) REFERENCES loan_products(id),
 CONSTRAINT fk_application_officer FOREIGN KEY(assigned_officer_id) REFERENCES app_users(id),
 CONSTRAINT ck_application_amount CHECK(requested_loan_amount>0 AND monthly_income>0 AND existing_emi>=0),
 CONSTRAINT ck_application_tenure CHECK(tenure_months BETWEEN 12 AND 360),
 CONSTRAINT ck_application_status CHECK(status IN ('SUBMITTED','DOCUMENT_PENDING','UNDER_REVIEW','APPROVED','REJECTED','SANCTIONED','DISBURSED')),
 CONSTRAINT ck_application_employment CHECK(employment_type IN ('SALARIED','SELF_EMPLOYED'))
);
CREATE INDEX ix_application_customer_date ON loan_applications(customer_id,application_date);
CREATE INDEX ix_application_officer_status ON loan_applications(assigned_officer_id,status);
CREATE INDEX ix_application_fingerprint ON loan_applications(customer_id,request_fingerprint);
CREATE TABLE loan_documents (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,application_id BIGINT NOT NULL,document_type VARCHAR(30) NOT NULL,original_filename VARCHAR(150) NOT NULL,
 storage_name VARCHAR(100) NOT NULL,content_type VARCHAR(40) NOT NULL,size_bytes BIGINT NOT NULL,uploaded_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
 verification_status VARCHAR(20) NOT NULL,verified_by_id BIGINT,verified_at TIMESTAMP(6) WITH TIME ZONE,verification_remarks VARCHAR(1000),
 CONSTRAINT uk_document_storage UNIQUE(storage_name),CONSTRAINT fk_document_application FOREIGN KEY(application_id) REFERENCES loan_applications(id),
 CONSTRAINT fk_document_verifier FOREIGN KEY(verified_by_id) REFERENCES app_users(id),
 CONSTRAINT ck_document_size CHECK(size_bytes>0 AND size_bytes<=5242880),
 CONSTRAINT ck_document_type CHECK(document_type IN ('IDENTITY_PROOF','ADDRESS_PROOF','INCOME_PROOF','BANK_STATEMENT','PROPERTY_DOCUMENT')),
 CONSTRAINT ck_document_verification CHECK(verification_status IN ('PENDING','VERIFIED','REJECTED'))
);
CREATE INDEX ix_document_application ON loan_documents(application_id,uploaded_at,id);
CREATE TABLE application_status_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,application_id BIGINT NOT NULL,from_status VARCHAR(30),to_status VARCHAR(30) NOT NULL,
 changed_by_id BIGINT NOT NULL,remarks VARCHAR(1000) NOT NULL,changed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
 CONSTRAINT fk_history_application FOREIGN KEY(application_id) REFERENCES loan_applications(id),
 CONSTRAINT fk_history_actor FOREIGN KEY(changed_by_id) REFERENCES app_users(id)
);
CREATE INDEX ix_history_application ON application_status_history(application_id,changed_at,id);
